/* Builds the generated parts of the site:
 *   HurricaneBrawl.html   play.html (the game) with its stylesheet and every script embedded, so the
 *                         game is one file that works anywhere, opened from disk or from any host
 *                         (three.js still comes from the jsDelivr CDN, so it needs an internet connection)
 *   index.html            the landing page's fighter cards and food chain, refreshed from js/storms.js
 *                         (between its <!-- fighters --> and <!-- chain --> markers)
 *   node tools/build.js
 * Edit the sources (play.html, css/, js/, the rest of index.html) and rebuild; don't edit the output. */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const safe = (code) => code.replace(/<\/(script)/gi, '<\\/$1');   // can't end the inline tag early
const SOURCE = 'play.html', OUTPUT = 'HurricaneBrawl.html';

const src = read(SOURCE);
let html = src, n = 0;
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) => { n++; return `<style>/* ${href} */\n${read(href)}\n</style>`; });
html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, s) => { n++; return `<script>/* ${s} */\n${safe(read(s))}\n</script>`; });
// the scripts the page's module loads after three.js go in as text/x-inline blocks it picks up
const list = html.match(/const APP_SCRIPTS = (\[[^\]]*\]);/);
if (!list) throw new Error(`APP_SCRIPTS list not found in ${SOURCE}`);
const appScripts = JSON.parse(list[1].replace(/'/g, '"'));
const blocks = appScripts.map((s) => { n++; return `<script type="text/x-inline" data-src="${s}">\n${safe(read(s))}\n</script>`; }).join('\n');
// function replacers only: a string replacement would treat "$$", "$'" etc. in the code as patterns
html = html.replace('<script type="module">', () => `${blocks}\n<script type="module">`);
html = html.replace('<!doctype html>', () => `<!doctype html>\n<!-- Generated by tools/build.js from ${SOURCE}, css/ and js/. Edit those and rebuild. -->`);

// every embedded file must appear verbatim
const sheets = [...src.matchAll(/<link rel="stylesheet" href="([^"]+)">/g)].map(m => m[1]);
const scripts = [...src.matchAll(/<script src="([^"]+)">/g)].map(m => m[1]);
for (const f of [...sheets, ...scripts, ...appScripts]) {
  const body = f.endsWith('.css') ? read(f) : safe(read(f));
  if (!html.includes(body)) throw new Error(`${f} was not embedded intact`);
}
fs.writeFileSync(path.join(root, OUTPUT), html);
console.log(`wrote ${OUTPUT}: ${n} files embedded, ${(html.length / 1024).toFixed(0)} KB`);

// ---------------------------------------------------------------- the landing page's generated parts
// index.html's fighter cards and its food chain are made from js/storms.js (the game's own numbers)
// between <!-- name:start --> and <!-- name:end --> markers; the rest of the page is written by hand.
global.BRAWL_EARTH_DATA = require(path.join(root, 'js/earth-data.js'));
global.BrawlEarth = require(path.join(root, 'js/earth.js'));
const S = require(path.join(root, 'js/storms.js'));
const E = global.BrawlEarth;
// the site's words and colours for each storm (the rest comes from storms.js)
const COPY = {
  hurricane: { epithet: 'The Eye of the Ocean', color: '#38c8e0' },
  tornado: { epithet: 'The Plains Ripper', color: '#c9b08e' },
  blizzard: { epithet: 'The Frozen Wall', color: '#bfe4ff' },
  sandstorm: { epithet: 'The Desert King', color: '#f0a94e' },
  supercell: { epithet: 'The Thunder Throne', color: '#a493ff' },
  wildfire: { epithet: 'The Burning Front', color: '#ff6a2b' },
};
const esc = (t) => String(t).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const punch = (t) => t.power * t.rMax * t.rMax;
const maxPunch = Math.max(...S.ORDER.map((k) => punch(S.TYPES[k])));
const terrain = (k) => E.TERRAINS[E.T[k]].label;
function fighters() {
  return S.ORDER.map((k) => {
    const d = S.TYPES[k], c = COPY[k], beats = S.beats(k), fears = S.beatenBy(k);
    const stats = [['Size', d.rMax / 760], ['Speed', d.speed / 560], ['Wrecking', punch(d) / maxPunch]].map(([n, v]) => [n, Math.round(v * 100)]);
    const home = Object.entries(d.gain).filter(([, g]) => g >= 3).sort((a, b) => b[1] - a[1]).map(([t]) => terrain(t).toLowerCase()).join(', ').replace(/^./, (c) => c.toUpperCase());
    return `
      <article class="fighter reveal" id="fighter-${k}" style="--c: ${c.color}">
        <figure class="f-portrait"><img src="media/fighters/${k}.jpg" width="640" height="640" loading="lazy" alt="The ${d.name.toLowerCase()} in the game, using its ${esc(d.special.name.toLowerCase())}"></figure>
        <div class="f-body">
          <p class="f-epithet">${esc(c.epithet)}</p>
          <h3>${d.name}</h3>
          <p class="f-blurb">${esc(d.blurb)}</p>
          <ul class="f-stats">${stats.map(([n, v]) => `<li style="--v: ${v / 100}"><span>${n}</span><i></i><b>${v}</b></li>`).join('')}</ul>
          <dl class="f-facts">
            <dt>Home turf</dt><dd>${esc(home)}</dd>
            <dt>Finisher</dt><dd><b>${esc(d.special.name)}</b> ${esc(d.special.text)}</dd>
            <dt>Beats</dt><dd><a href="#fighter-${beats}" style="--c: ${COPY[beats].color}">${S.TYPES[beats].name}</a></dd>
            <dt>Fears</dt><dd><a href="#fighter-${fears}" style="--c: ${COPY[fears].color}">${S.TYPES[fears].name}</a></dd>
          </dl>
        </div>
      </article>`;
  }).join('') + '\n      ';
}
// the food chain: a ring of the six, each with an arrow to the one it beats, and the reasons
function chain() {
  const n = S.CIRCLE.length, cx = 300, cy = 300, rr = 205, node = 58;
  const pos = S.CIRCLE.map((k, i) => { const a = -Math.PI / 2 + i * 2 * Math.PI / n; return [cx + rr * Math.cos(a), cy + rr * Math.sin(a)]; });
  const arcs = S.CIRCLE.map((k, i) => {
    const [x0, y0] = pos[i], [x1, y1] = pos[(i + 1) % n];
    // from the edge of one node to the edge of the next, bowed outward
    const a0 = Math.atan2(y1 - y0, x1 - x0), sx = x0 + Math.cos(a0) * (node + 10), sy = y0 + Math.sin(a0) * (node + 10), ex = x1 - Math.cos(a0) * (node + 16), ey = y1 - Math.sin(a0) * (node + 16);
    const mx = (sx + ex) / 2, my = (sy + ey) / 2, ox = mx - cx, oy = my - cy, ol = Math.hypot(ox, oy);
    return `<path d="M${sx.toFixed(1)} ${sy.toFixed(1)} Q${(mx + ox / ol * 34).toFixed(1)} ${(my + oy / ol * 34).toFixed(1)} ${ex.toFixed(1)} ${ey.toFixed(1)}" stroke="${COPY[k].color}" />`;
  }).join('');
  const nodes = S.CIRCLE.map((k, i) => {
    const [x, y] = pos[i];
    return `<g class="node"><clipPath id="clip-${k}"><circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${node}"/></clipPath>` +
      `<image href="media/fighters/${k}.jpg" x="${(x - node).toFixed(1)}" y="${(y - node).toFixed(1)}" width="${node * 2}" height="${node * 2}" clip-path="url(#clip-${k})" preserveAspectRatio="xMidYMid slice"/>` +
      `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${node}" fill="none" stroke="${COPY[k].color}" stroke-width="5"/>` +
      `<text x="${x.toFixed(1)}" y="${(y + node + 26).toFixed(1)}">${S.TYPES[k].name}</text></g>`;
  }).join('');
  const svg = `<svg class="chain-ring" viewBox="0 0 600 640" role="img" aria-label="The food chain: ${S.CIRCLE.map((k) => S.TYPES[k].name).join(' beats ')} beats ${S.TYPES[S.CIRCLE[0]].name}">
          <defs><marker id="tip" viewBox="0 0 10 10" refX="6" refY="5" markerWidth="5" markerHeight="5" orient="auto-start-reverse"><path d="M0 0L10 5L0 10z" fill="context-stroke"/></marker></defs>
          <g class="arcs" fill="none" stroke-width="7" stroke-linecap="round" marker-end="url(#tip)">${arcs}</g>${nodes}
        </svg>`;
  const list = S.CIRCLE.map((k) => {
    const b = S.beats(k);
    return `<li class="vs reveal" style="--a: ${COPY[k].color}; --b: ${COPY[b].color}"><p><b class="a">${S.TYPES[k].name}</b> <span>beats</span> <b class="b">${S.TYPES[b].name}</b></p><small>${esc(S.WHY[k])}.</small></li>`;
  }).join('');
  return `\n        ${svg}\n        <ol class="chain-list">${list}</ol>\n      `;
}
const page = 'index.html';
let landing = read(page);
const fill = (name, html) => {
  const re = new RegExp(`(<!-- ${name}:start -->)[\\s\\S]*?(<!-- ${name}:end -->)`);
  if (!re.test(landing)) throw new Error(`${page} has no ${name} markers`);
  landing = landing.replace(re, (_, a, b) => a + html + b);
};
fill('fighters', fighters());
fill('chain', chain());
fs.writeFileSync(path.join(root, page), landing);
console.log(`refreshed ${page}: ${S.ORDER.length} fighter cards and the food chain, from js/storms.js`);
